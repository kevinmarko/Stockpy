"""Per-field liveness/safety metadata for the Pilots API's settings editors.

Answers, for one ``Settings`` field, the question an operator actually has in
front of a settings form: **"if I change this and press Save, what happens?"**

Until this module existed the five ``/settings/*`` editors in
``api/pilots_api.py`` all answered that with one hardcoded, screen-wide string
— ``"applies": "next_daemon_restart"`` — which was a true statement about a
pure ``.env`` write and is no longer true now that ``runtime_flags`` can apply
a change to the running process. This module replaces the guess with the four
real answers, per field:

``immediately``
    A live change is observed. Every attributable read of this field is a
    *fresh* read (``docs/settings_liveness.json``'s ``live_safe`` bucket), so
    the write path may additionally push it onto the running process's own
    ``settings`` singleton via ``runtime_flags_writer.write_override``.

``next_daemon_restart``
    At least one read *captures* the value — an import-time constant, a
    constructor field, a decorator argument, an ``os.environ`` read. The
    ``.env`` write is durable but the running process keeps the old value.
    :func:`restart_reason` renders WHY, and :func:`capture_sites` names the
    exact ``file:line`` sites so the claim is checkable rather than trusted.

``no_effect``
    The field has zero production reads and its name never appears as a string
    literal in production code. Writing it does nothing, ever.

``env_pinned``
    A real shell export (``SOME_FIELD=x python3 main.py``) is live for this
    field right now. That always wins over both the runtime store and ``.env``,
    regardless of what the static classifier says — so this is a DOWNGRADE
    applied on top of the classification, never a classification of its own.

--------------------------------------------------------------------------
Fresh-per-request vs. cached
--------------------------------------------------------------------------
The two halves have genuinely different lifetimes and must not be conflated:

* The **classification** (``live_safe``/``restart_required``/``no_op``) is a
  static property of the source tree, committed to ``docs/settings_liveness.json``
  and regenerated by ``scripts/settings_liveness.py``. It cannot change while a
  process runs, so it is parsed once and cached (:func:`load_liveness`).
* **Env-pinning** and **store membership** are per-process, per-moment facts.
  An operator can create ``output/runtime_flags.json`` between two requests.
  :func:`env_pinned_keys` and :func:`runtime_store_keys` therefore delegate to
  ``runtime_flags`` on EVERY call and are deliberately not cached. Baking
  either into a static artifact would be exactly the kind of stale claim this
  module exists to eliminate.

--------------------------------------------------------------------------
Honesty rules this module follows
--------------------------------------------------------------------------
* **Never fabricates** (CONSTRAINT #4). ``capture_sites`` returns ``[]`` for a
  ``live_safe`` field because that is the measured answer — "the classifier
  found nothing capturing this" — and ``[]`` is deliberately distinguishable
  from the artifact being unreadable. ``restart_reason`` is ``None`` for any
  field that does not need a restart, never a filler string.
* **Never raises** (CONSTRAINT #6). A missing, corrupt, or wrong-shaped
  artifact degrades to :data:`CLASSIFICATION_UNKNOWN` with a WARNING.
* **An unknown classification reports — and behaves as —
  ``next_daemon_restart``.** This is not a guess dressed as a measurement. The
  SAME classification drives the write path: a field this module cannot
  classify is never live-applied, so "your change takes effect at the next
  restart" is true *by construction* rather than by assumption. It also matches
  the direction ``scripts/settings_liveness.py`` itself fails in ("it prefers a
  false ``restart_required`` over a false ``live_safe``"). ``restart_reason``
  says plainly that the artifact was unreadable instead of inventing a site.

--------------------------------------------------------------------------
Module constraints
--------------------------------------------------------------------------
* Dependency-light read helper on the API path: stdlib + ``runtime_flags`` +
  ``settings_keysets`` only. It never imports ``settings``, and never imports
  any heavy calculation engine (``pilots/`` modules are AST-guarded against
  those — see ``tests/test_pilots_forecast_skill.py``).
* **Contains no ``Settings`` field-name string literals, deliberately.**
  ``scripts/settings_liveness.py`` scans production files for exact field-name
  literals to decide whether a field with no attributable read is genuinely
  ``no_op`` or is reached through a name-driven dispatcher. A prose table keyed
  by field name in here would register as a phantom read site for every field
  it named and corrupt the very artifact this module consumes. Everything below
  is keyed by CLASSIFIER RULE name instead.
* Path anchoring: the artifact is located from THIS FILE, never from the
  process CWD (same rule as ``runtime_flags.DEFAULT_STORE_PATH`` — a real bug in
  this repo once had an upward path search escape a git worktree).
"""

