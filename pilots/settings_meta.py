# Assembly
# ---------------------------------------------------------------------------
def applies_for(
    key: str,
    *,
    pinned: FrozenSet[str],
    data: Optional[Dict[str, Any]] = None,
    live_apply: bool = True,
) -> str:
    """The field's ``applies`` state.

    Derived from the static classification, then adjusted by two facts the
    classification cannot know, in this order:

    1. A real shell export live for this name downgrades to
       :data:`APPLIES_ENV_PINNED` — it wins over both the runtime store and
       ``.env`` regardless of what the classifier says, so it is checked first.
    2. ``live_apply=False`` (no writer in this checkout — see
       :func:`live_apply_available`) downgrades ``immediately`` to
       ``next_daemon_restart``. ``no_effect`` is untouched: a field nothing
       reads still does nothing whether or not a writer exists.
    """
    if key.upper() in pinned:
        return APPLIES_ENV_PINNED
    applies = _CLASSIFICATION_TO_APPLIES[classification(key, data=data)]
    if applies == APPLIES_IMMEDIATELY and not live_apply:
        return APPLIES_NEXT_RESTART
    return applies


def field_metadata(
    key: str,
    *,
    pinned: FrozenSet[str],
    stored: FrozenSet[str],
    data: Optional[Dict[str, Any]] = None,
    live_apply: bool = True,
) -> Dict[str, Any]:
    """The ``liveness`` sub-object attached to one field in a ``GET /settings/*``
    payload.

    ``pinned`` / ``stored`` / ``live_apply`` are passed in rather than looked up
    here so ONE request computes each once for all ~49 of its fields — but they
    are still computed fresh for that request (see :func:`env_pinned_keys`).
    """
    d = data if data is not None else load_liveness()
    is_pinned = key.upper() in pinned
    applies = applies_for(key, pinned=pinned, data=d, live_apply=live_apply)
    # A restart reason is about the CLASSIFICATION, so it is still reported for
    # an env-pinned field: the pin is the immediate blocker, but the capture
    # site is still true and still relevant once the pin is removed.
    reason = restart_reason(key, data=d)
    if (
        reason is None
        and applies == APPLIES_NEXT_RESTART
        and classification(key, data=d) == "live_safe"
    ):
        # Live-safe, but this build cannot apply it live. Say which of the two
        # it is rather than leaving a restart claim with no explanation.
        reason = _NO_WRITER_REASON
    return {
        "applies": applies,
        "restart_reason": reason,
        "capture_sites": capture_sites(key, data=d),
        "env_pinned": is_pinned,
        "dangerous": is_dangerous(key),
        # Raw membership in ``stored`` is NOT enough: a pin always wins over
        # the store (see applies_for's own ordering, checked first there for
        # the same reason), so a key that is BOTH stored and pinned is
        # currently active from the real shell export, not the store --
        # reporting "runtime_store" for it would contradict this same
        # payload's own "env_pinned": true one line up. A store entry can
        # also be a stale/invalid leftover the last apply skipped (e.g. a
        # field whose bounds changed after it was written, or the file
        # edited by hand) -- ``bootstrap`` keys are refused by the writer so
        # they can never legitimately reach the store at all. Neither of
        # those is applied either, so neither may claim this source.
        "source": (
            SOURCE_RUNTIME_STORE if (key in stored and not is_pinned) else SOURCE_ENV_FILE
        ),
    }


def summarize_applies(states: List[str]) -> Dict[str, Any]:
    """Roll a screen's per-field ``applies`` states into one honest summary.

    Returns ``{"applies": <summary>, "applies_counts": {state: n, ...}}``.
    The summary is the single shared state when every field agrees, ``"mixed"``
    when they do not, and — for a screen with no fields at all — ``"mixed"``
    would be a claim about nothing, so an empty screen reports
    ``next_daemon_restart`` (the conservative direction, matching the rest of
    this module).
    """
    counts = {state: 0 for state in APPLIES_STATES}
    for state in states:
        if state in counts:
            counts[state] += 1
    distinct = {s for s, n in counts.items() if n}
    if len(distinct) == 1:
        summary = next(iter(distinct))
    elif not distinct:
        summary = APPLIES_NEXT_RESTART
    else:
        summary = "mixed"
    return {"applies": summary, "applies_counts": counts}
